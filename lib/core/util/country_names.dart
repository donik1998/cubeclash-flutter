/// `'UZ'` → `'Uzbekistan'`. Null for an unknown, malformed or absent code, so
/// callers can omit the line rather than render a placeholder.
String? countryCodeToName(String? code) {
  if (code == null) return null;
  final String upper = code.trim().toUpperCase();
  if (upper.length != 2) return null;
  return kCountryNames[upper];
}
